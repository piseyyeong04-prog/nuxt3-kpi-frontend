// utils/pdfReportGenerator.ts
import jsPDF from 'jspdf';
import 'jspdf-autotable';
import dayjs from 'dayjs';
import type { ActivityItem } from '~/types/activity';

// Extend jsPDF interface to include autoTable
declare module 'jspdf' {
  interface jsPDF {
    autoTable: (options: any) => jsPDF;
    lastAutoTable: {
      finalY: number;
    };
  }
}

interface PDFGenerationOptions {
  title?: string;
  subtitle?: string;
  dateRange?: string;
  companyName?: string;
  companyLogo?: string;
  generatedBy?: string;
  includeCharts?: boolean;
  customStyles?: {
    primaryColor?: string;
    secondaryColor?: string;
  };
}

export class ActivityReportGenerator {
  private doc: jsPDF;
  private pageWidth: number;
  private pageHeight: number;
  private margin: number;
  private primaryColor: string;
  private secondaryColor: string;
  private headerHeight: number;

  constructor(options: PDFGenerationOptions = {}) {
    this.doc = new jsPDF('p', 'mm', 'a4');
    this.pageWidth = this.doc.internal.pageSize.getWidth();
    this.pageHeight = this.doc.internal.pageSize.getHeight();
    this.margin = 25;
    this.primaryColor = options.customStyles?.primaryColor || '#1E40AF';
    this.secondaryColor = options.customStyles?.secondaryColor || '#7C3AED';
    this.headerHeight = 70;
  }

  private hexToRgb(hex: string): [number, number, number] {
    const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
    return result 
      ? [parseInt(result[1], 16), parseInt(result[2], 16), parseInt(result[3], 16)]
      : [30, 64, 175]; // Default blue
  }

  private addHeader(options: PDFGenerationOptions) {
    const [r, g, b] = this.hexToRgb(this.primaryColor);
    const [sr, sg, sb] = this.hexToRgb(this.secondaryColor);
    
    // Modern gradient-style header background
    this.doc.setFillColor(r, g, b);
    this.doc.rect(0, 0, this.pageWidth, this.headerHeight, 'F');
    
    // Add subtle accent line
    this.doc.setFillColor(sr, sg, sb);
    this.doc.rect(0, this.headerHeight - 4, this.pageWidth, 4, 'F');

    // Company logo area with modern design
    if (options.companyLogo) {
      // Modern logo placeholder
      this.doc.setFillColor(255, 255, 255);
      this.doc.roundedRect(this.margin, 20, 40, 30, 6, 6, 'F');
      
      this.doc.setFillColor(r, g, b);
      this.doc.setFontSize(16);
      this.doc.setFont('helvetica', 'bold');
      this.doc.text('LOGO', this.margin + 20, 38, { align: 'center' });
    }

    // Modern typography for company name and title
    this.doc.setTextColor(255, 255, 255);
    this.doc.setFontSize(28);
    this.doc.setFont('helvetica', 'bold');
    const titleX = options.companyLogo ? this.margin + 50 : this.margin;
    this.doc.text(options.companyName || 'Activity Report', titleX, 30);

    this.doc.setFontSize(14);
    this.doc.setFont('helvetica', 'normal');
    this.doc.setTextColor(220, 220, 220);
    this.doc.text(options.subtitle || 'System Activity Analysis', titleX, 42);

    // Professional date formatting with icons effect
    this.doc.setFontSize(11);
    this.doc.setFont('helvetica', 'normal');
    this.doc.setTextColor(200, 200, 200);
    this.doc.text(`📅 Generated: ${dayjs().format('MMMM DD, YYYY • HH:mm')}`, titleX, 54);
    
    if (options.dateRange) {
      this.doc.text(`📊 Report Period: ${options.dateRange}`, titleX, 62);
    }

    // Reset text color
    this.doc.setTextColor(0, 0, 0);
  }

  private addFooter(pageNumber: number, totalPages: number, generatedBy?: string) {
    const footerY = this.pageHeight - 20;
    const [r, g, b] = this.hexToRgb(this.primaryColor);
    
    // Modern footer design with subtle line
    this.doc.setDrawColor(230, 230, 230);
    this.doc.setLineWidth(0.8);
    this.doc.line(this.margin, footerY - 8, this.pageWidth - this.margin, footerY - 8);

    // Professional footer text
    this.doc.setFontSize(9);
    this.doc.setFont('helvetica', 'normal');
    this.doc.setTextColor(120, 120, 120);
    
    // Page numbers in modern format
    const pageText = `${pageNumber} / ${totalPages}`;
    this.doc.text(pageText, this.pageWidth - this.margin, footerY, { align: 'right' });

    // Generated by information
    if (generatedBy) {
      this.doc.text(`Generated by ${generatedBy}`, this.margin, footerY);
    }
    
    // Add timestamp in footer
    this.doc.text(dayjs().format('DD/MM/YYYY HH:mm'), this.pageWidth / 2, footerY, { align: 'center' });
  }

  private addSummarySection(data: ActivityItem[]) {
    let currentY = this.headerHeight + 25;
    const [r, g, b] = this.hexToRgb(this.primaryColor);

    // Modern section header with accent
    this.doc.setFillColor(250, 251, 252);
    this.doc.roundedRect(this.margin - 5, currentY - 10, this.pageWidth - 2 * this.margin + 10, 20, 4, 4, 'F');
    
    this.doc.setFillColor(r, g, b);
    this.doc.roundedRect(this.margin - 5, currentY - 10, 6, 20, 3, 3, 'F');

    this.doc.setFontSize(18);
    this.doc.setFont('helvetica', 'bold');
    this.doc.setTextColor(r, g, b);
    this.doc.text('📊 Executive Summary', this.margin + 5, currentY - 1);

    currentY += 20;

    // Calculate stats with better organization
    const stats = this.calculateStats(data);
    
    // Create modern card-style summary boxes
    const summaryCards = [
      { label: 'Total Activities', value: stats.total.toString(), color: [59, 130, 246] },
      { label: 'Login Events', value: stats.logins.toString(), color: [16, 185, 129] },
      { label: 'Create Actions', value: stats.creates.toString(), color: [245, 158, 11] },
      { label: 'Update Actions', value: stats.updates.toString(), color: [139, 92, 246] },
      { label: 'Delete Actions', value: stats.deletes.toString(), color: [239, 68, 68] },
      { label: 'Unique Users', value: stats.uniqueUsers.toString(), color: [6, 182, 212] }
    ];

    // Draw summary cards in a grid
    let cardX = this.margin;
    let cardY = currentY;
    const cardWidth = (this.pageWidth - 2 * this.margin - 10) / 2;
    const cardHeight = 25;

    summaryCards.forEach((card, index) => {
      if (index > 0 && index % 2 === 0) {
        cardY += cardHeight + 8;
        cardX = this.margin;
      }

      // Card background with subtle shadow effect
      this.doc.setFillColor(248, 250, 252);
      this.doc.roundedRect(cardX, cardY, cardWidth, cardHeight, 4, 4, 'F');
      
      // Color accent bar
      this.doc.setFillColor(card.color[0], card.color[1], card.color[2]);
      this.doc.roundedRect(cardX + 2, cardY + 2, 4, cardHeight - 4, 2, 2, 'F');

      // Card text
      this.doc.setFontSize(11);
      this.doc.setFont('helvetica', 'normal');
      this.doc.setTextColor(100, 116, 139);
      this.doc.text(card.label, cardX + 12, cardY + 10);

      this.doc.setFontSize(16);
      this.doc.setFont('helvetica', 'bold');
      this.doc.setTextColor(30, 41, 59);
      this.doc.text(card.value, cardX + 12, cardY + 20);

      cardX += cardWidth + 10;
    });

    currentY = cardY + cardHeight + 20;

    // Additional insights section
    if (stats.mostActiveUser || stats.peakHour) {
      this.doc.setFillColor(245, 247, 250);
      this.doc.roundedRect(this.margin, currentY, this.pageWidth - 2 * this.margin, 30, 6, 6, 'F');

      this.doc.setFontSize(12);
      this.doc.setFont('helvetica', 'bold');
      this.doc.setTextColor(r, g, b);
      this.doc.text('💡 Key Insights', this.margin + 10, currentY + 12);

      this.doc.setFontSize(10);
      this.doc.setFont('helvetica', 'normal');
      this.doc.setTextColor(71, 85, 105);
      
      if (stats.mostActiveUser) {
        this.doc.text(`👤 Most Active: ${stats.mostActiveUser}`, this.margin + 10, currentY + 20);
      }
      
      if (stats.peakHour) {
        this.doc.text(`⏰ Peak Activity: ${stats.peakHour}`, this.margin + 10, currentY + 26);
      }

      currentY += 40;
    }

    return currentY;
  }

  private addActivityTable(data: ActivityItem[], startY: number) {
    const [r, g, b] = this.hexToRgb(this.primaryColor);
    
    // Modern section header
    this.doc.setFillColor(250, 251, 252);
    this.doc.roundedRect(this.margin - 5, startY - 10, this.pageWidth - 2 * this.margin + 10, 20, 4, 4, 'F');
    
    this.doc.setFillColor(r, g, b);
    this.doc.roundedRect(this.margin - 5, startY - 10, 6, 20, 3, 3, 'F');

    this.doc.setFontSize(18);
    this.doc.setFont('helvetica', 'bold');
    this.doc.setTextColor(r, g, b);
    this.doc.text('📋 Activity Details', this.margin + 5, startY - 1);

    startY += 15;

    // Prepare table data with better formatting
    const tableData = data.slice(0, 50).map((item, index) => [
      `#${(index + 1).toString().padStart(2, '0')}`,
      this.capitalizeFirst(item.action),
      item.collection || 'N/A',
      dayjs(item.timestamp).format('MMM DD'),
      dayjs(item.timestamp).format('HH:mm'),
      `${item.user?.first_name || ''} ${item.user?.last_name || ''}`.trim() || 'System User',
      item.user?.title || 'N/A'
    ]);

    if (typeof this.doc.autoTable === 'function') {
      this.doc.autoTable({
        startY: startY,
        head: [['#', 'Action', 'Collection', 'Date', 'Time', 'User', 'Role']],
        body: tableData,
        theme: 'plain',
        headStyles: {
          fillColor: [r, g, b],
          textColor: [255, 255, 255],
          fontSize: 10,
          fontStyle: 'bold',
          cellPadding: { top: 8, bottom: 8, left: 6, right: 6 }
        },
        bodyStyles: {
          fontSize: 9,
          textColor: [51, 65, 85],
          cellPadding: { top: 6, bottom: 6, left: 6, right: 6 }
        },
        alternateRowStyles: {
          fillColor: [248, 250, 252]
        },
        columnStyles: {
          0: { cellWidth: 15, halign: 'center', fontStyle: 'bold' },
          1: { cellWidth: 22, halign: 'center' },
          2: { cellWidth: 28 },
          3: { cellWidth: 20, halign: 'center' },
          4: { cellWidth: 18, halign: 'center' },
          5: { cellWidth: 35 },
          6: { cellWidth: 30 }
        },
        margin: { left: this.margin, right: this.margin },
        tableLineColor: [229, 231, 235],
        tableLineWidth: 0.5,
        didParseCell: (data: any) => {
          // Modern action styling with better colors
          if (data.column.index === 1 && data.section === 'body') {
            const action = data.cell.text[0].toLowerCase();
            switch (action) {
              case 'login':
                data.cell.styles.fillColor = [219, 234, 254];
                data.cell.styles.textColor = [29, 78, 216];
                data.cell.styles.fontStyle = 'bold';
                break;
              case 'create':
                data.cell.styles.fillColor = [209, 250, 229];
                data.cell.styles.textColor = [21, 128, 61];
                data.cell.styles.fontStyle = 'bold';
                break;
              case 'update':
                data.cell.styles.fillColor = [254, 240, 138];
                data.cell.styles.textColor = [146, 64, 14];
                data.cell.styles.fontStyle = 'bold';
                break;
              case 'delete':
                data.cell.styles.fillColor = [254, 226, 226];
                data.cell.styles.textColor = [185, 28, 28];
                data.cell.styles.fontStyle = 'bold';
                break;
            }
          }
          
          // Style the index column
          if (data.column.index === 0 && data.section === 'body') {
            data.cell.styles.textColor = [100, 116, 139];
            data.cell.styles.fontSize = 8;
          }
        }
      });
    } else {
      // Enhanced fallback with better formatting
      this.doc.setFillColor(248, 250, 252);
      this.doc.roundedRect(this.margin, startY, this.pageWidth - 2 * this.margin, 15, 4, 4, 'F');
      
      this.doc.setFontSize(10);
      this.doc.setFont('helvetica', 'bold');
      this.doc.setTextColor(r, g, b);
      this.doc.text('#    Action      Collection        Date        Time    User', this.margin + 5, startY + 10);
      
      startY += 20;
      this.doc.setFont('helvetica', 'normal');
      this.doc.setTextColor(51, 65, 85);
      
      const limitedData = tableData.slice(0, 250);
      limitedData.forEach((row, index) => {
        const text = `${row[0]}   ${row[1].padEnd(10)}  ${row[2].padEnd(15)} ${row[3].padEnd(10)} ${row[4].padEnd(6)} ${row[5]}`;
        
        if (index % 2 === 0) {
          this.doc.setFillColor(248, 250, 252);
          this.doc.rect(this.margin, startY - 3, this.pageWidth - 2 * this.margin, 8, 'F');
        }
        
        this.doc.text(text, this.margin + 5, startY + 2);
        startY += 8;
        
        if (startY > this.pageHeight - 50) {
          this.doc.addPage();
          startY = 40;
        }
      });
    }
  }

  private calculateStats(data: ActivityItem[]) {
    const stats = {
      total: data.length,
      logins: 0,
      creates: 0,
      updates: 0,
      deletes: 0,
      uniqueUsers: 0,
      mostActiveUser: '',
      peakHour: ''
    };

    const userCounts: Record<string, number> = {};
    const hourCounts: Record<number, number> = {};

    data.forEach(item => {
      // Count actions
      switch (item.action.toLowerCase()) {
        case 'login': stats.logins++; break;
        case 'create': stats.creates++; break;
        case 'update': stats.updates++; break;
        case 'delete': stats.deletes++; break;
      }

      // Count users
      const userName = `${item.user?.first_name || ''} ${item.user?.last_name || ''}`.trim();
      if (userName && userName !== 'System User') {
        userCounts[userName] = (userCounts[userName] || 0) + 1;
      }

      // Count hours
      const hour = dayjs(item.timestamp).hour();
      hourCounts[hour] = (hourCounts[hour] || 0) + 1;
    });

    stats.uniqueUsers = Object.keys(userCounts).length;
    
    // Find most active user
    const mostActive = Object.entries(userCounts).sort((a, b) => b[1] - a[1])[0];
    stats.mostActiveUser = mostActive ? `${mostActive[0]} (${mostActive[1]} activities)` : '';

    // Find peak hour with better formatting
    const peakHourEntry = Object.entries(hourCounts).sort((a, b) => b[1] - a[1])[0];
    if (peakHourEntry) {
      const hour = parseInt(peakHourEntry[0]);
      const count = peakHourEntry[1];
      const formattedTime = hour < 12 ? `${hour || 12}:00 AM` : 
                           hour === 12 ? '12:00 PM' : `${hour - 12}:00 PM`;
      stats.peakHour = `${formattedTime} (${count} activities)`;
    }

    return stats;
  }

  private capitalizeFirst(str: string): string {
    return str.charAt(0).toUpperCase() + str.slice(1).toLowerCase();
  }

  private addChartSection(data: ActivityItem[], startY: number) {
    const [r, g, b] = this.hexToRgb(this.primaryColor);
    
    // Modern chart section header
    this.doc.setFillColor(250, 251, 252);
    this.doc.roundedRect(this.margin - 5, startY - 10, this.pageWidth - 2 * this.margin + 10, 20, 4, 4, 'F');
    
    this.doc.setFillColor(r, g, b);
    this.doc.roundedRect(this.margin - 5, startY - 10, 6, 20, 3, 3, 'F');

    this.doc.setFontSize(18);
    this.doc.setFont('helvetica', 'bold');
    this.doc.setTextColor(r, g, b);
    this.doc.text('📈 Activity Trends', this.margin + 5, startY - 1);

    startY += 15;

    // Modern chart placeholder with gradient effect
    this.doc.setFillColor(248, 250, 252);
    this.doc.roundedRect(this.margin, startY, this.pageWidth - 2 * this.margin, 80, 8, 8, 'F');
    
    // Inner border for modern look
    this.doc.setDrawColor(226, 232, 240);
    this.doc.setLineWidth(1);
    this.doc.roundedRect(this.margin + 5, startY + 5, this.pageWidth - 2 * this.margin - 10, 70, 6, 6, 'D');
    
    this.doc.setFontSize(14);
    this.doc.setFont('helvetica', 'normal');
    this.doc.setTextColor(148, 163, 184);
    this.doc.text('📊 Interactive charts available in digital version', this.pageWidth / 2, startY + 35, { align: 'center' });
    
    this.doc.setFontSize(10);
    this.doc.text('Chart visualizations include activity trends, user analytics, and time-based patterns', 
                  this.pageWidth / 2, startY + 48, { align: 'center' });

    return startY + 90;
  }

  public generateReport(data: ActivityItem[], options: PDFGenerationOptions = {}): void {
    // Add header
    this.addHeader(options);

    // Add summary section
    const afterSummaryY = this.addSummarySection(data);

    // Check if we need a new page
    let currentY = afterSummaryY;
    if (currentY > this.pageHeight - 120) {
      this.doc.addPage();
      currentY = 40;
    }

    // Add activity table
    this.addActivityTable(data, currentY);

    // Add charts if requested
    if (options.includeCharts) {
      let afterTableY = currentY + 120;
      if (this.doc.lastAutoTable && this.doc.lastAutoTable.finalY) {
        afterTableY = this.doc.lastAutoTable.finalY + 30;
      }
      
      if (afterTableY > this.pageHeight - 120) {
        this.doc.addPage();
        this.addChartSection(data, 40);
      } else {
        this.addChartSection(data, afterTableY);
      }
    }

    // Add footer to all pages
    const pageCount = this.doc.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      this.doc.setPage(i);
      this.addFooter(i, pageCount, options.generatedBy);
    }
  }

  public save(filename?: string): void {
    const defaultFilename = `activity-report-${dayjs().format('YYYY-MM-DD-HHmm')}.pdf`;
    this.doc.save(filename || defaultFilename);
  }

  public getBlob(): Blob {
    return this.doc.output('blob');
  }

  public getBase64(): string {
    return this.doc.output('datauristring');
  }
}

// Composable for easier use in Nuxt
export const usePDFReport = () => {
  const generateActivityReport = async (
    data: ActivityItem[], 
    options: PDFGenerationOptions = {}
  ) => {
    try {
      const generator = new ActivityReportGenerator(options);
      generator.generateReport(data, options);
      generator.save();
      
      console.log('PDF report generated successfully!');
    } catch (error) {
      console.error('Error generating PDF report:', error);
      throw error;
    }
  };

  return {
    generateActivityReport,
    ActivityReportGenerator
  };
};